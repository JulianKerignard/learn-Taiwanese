import type { Segment, VocabularyItem } from "@/types";

/**
 * One sentence of a graded text.
 *
 * `segments` carries the furigana placement for the whole sentence: the runs
 * concatenate back to `japanese`, and their readings concatenate back to `kana`.
 * Without it a reading would be stretched over the entire sentence, which is
 * useless — see toSegments() in lib/japanese.
 */
export interface ReadingSentence {
  japanese: string;
  /** Full reading in kana, punctuation and katakana kept as written. */
  kana: string;
  romaji: string;
  french: string;
  segments?: Segment[];
}

/** A word listed under the text. `isNew` drives the highlight and the flashcard button. */
export interface ReadingVocabulary extends VocabularyItem {
  isNew: boolean;
}

export interface GradedText {
  id: string;
  /** 1 = N5, 2 = N4, 3 = N3. */
  level: 1 | 2 | 3;
  title: string;
  titleFr: string;
  /** Running text, derived from the sentences — never edited by hand. */
  text: string;
  sentences: ReadingSentence[];
  vocabulary: ReadingVocabulary[];
  culturalNote?: string;
}

