const metaById = new Map(allUnitMetas.map((unit) => [unit.id, unit]));

export function getUnitMetaById(id: string): CourseUnitMeta | undefined {
  return metaById.get(id);
}

export function getChapter(num: number): Chapter | undefined {
  return chapters.find((c) => c.number === num);
}

export function getChapterUnitMetas(chapterNumber: number): CourseUnitMeta[] {
  const chapter = getChapter(chapterNumber);
  if (!chapter) return [];
  return chapter.unitIds
    .map((id) => metaById.get(id))
    .filter((u): u is CourseUnitMeta => u !== undefined);
}

// ── HSK / TOCFL Levels ──────────────────────────────────────────────

export function getHSKLevel(levelNumber: number): HSKLevel | undefined {
  return hskLevels.find((l) => l.level === levelNumber);
}

export function getHSKLevelForUnit(unit: CourseUnitMeta): HSKLevel | undefined {
  return hskLevels.find((l) => l.chapterNumbers.includes(unit.chapter));
}

export function getHSKLevelUnitMetas(level: HSKLevel): CourseUnitMeta[] {
  return level.chapterNumbers.flatMap((n) => getChapterUnitMetas(n));
}

export function getHSKLevelChapters(level: HSKLevel): Chapter[] {
  return level.chapterNumbers
    .map((n) => getChapter(n))
    .filter((c): c is Chapter => c !== undefined);
}
